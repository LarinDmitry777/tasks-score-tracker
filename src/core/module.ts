/**
 * Контракт модуля приложения.
 *
 * Приложение — агрегатор жизни: набор независимых модулей (задачи, уборка,
 * и т.д.). Каждый модуль самодостаточен и описывает себя этим объектом.
 * Ядро знает о модулях только через этот контракт.
 */

import type { ComponentType } from 'react';

export interface LifeModule {
  /** Уникальный идентификатор (латиница, kebab-case). Используется в URL/хранилище. */
  id: string;

  /** Отображаемое название на плитке дашборда. */
  title: string;

  /** Короткое описание/подзаголовок для плитки. */
  description: string;

  /** Имя иконки из спрайта (public/icons.svg) или эмодзи-фолбэк. */
  icon: string;

  /** Акцентный цвет плитки (CSS-значение). */
  accent: string;

  /** Экран модуля, рендерится при входе в модуль. */
  Screen: ComponentType;

  /**
   * Опциональная сводка для плитки дашборда (например «3 задачи на утро»).
   * Вызывается при рендере дашборда; должна быть дешёвой и синхронной.
   */
  useSummary?: () => ModuleSummary | null;
}

export interface ModuleSummary {
  /** Крупный акцент — число или короткая метка (например «3»). */
  value: string;
  /** Подпись под значением (например «осталось сегодня»). */
  label: string;
}
